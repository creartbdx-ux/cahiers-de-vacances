const byId = new Map(PAGE_ARCHETYPES.map((a) => [a.id, a]))

export function getArchetype(id: string): PageArchetype {
  const a = byId.get(id)
  if (!a) throw new Error(`Unknown page archetype: ${id}`)
  return a
}

export function listArchetypesByFamily(family: PageArchetype["family"]): PageArchetype[] {
  return PAGE_ARCHETYPES.filter((a) => a.family === family)
}

